const ARABIC_MONTHS = { Jan: 'يناير', Feb: 'فبراير', Mar: 'مارس', Apr: 'أبريل', May: 'مايو', Jun: 'يونيو', Jul: 'يوليو', Aug: 'أغسطس', Sep: 'سبتمبر', Oct: 'أكتوبر', Nov: 'نوفمبر', Dec: 'ديسمبر' }

export function translateAivex(value, language = 'en') {
  if (language !== 'ar' || value == null) return value
  const source = String(value)
  if (ARABIC[source]) return ARABIC[source]
  return Object.entries(ARABIC_MONTHS).reduce((text, [month, translation]) => text.replace(new RegExp(`\\b${month}\\b`, 'g'), translation), source)
    .replace(/^Today\b/, 'اليوم')
    .replace(/^Yesterday\b/, 'أمس')
}

export function aivexPath(path, language) {
  if (language !== 'ar') return path
  const separator = path.includes('?') ? '&' : '?'
  return `${path}${separator}lang=ar`
}

export function useAivexLocale() {
  const [params, setParams] = useSearchParams()
  const language = params.get('lang') === 'ar' ? 'ar' : 'en'
  const isArabic = language === 'ar'
  const t = useCallback((value) => translateAivex(value, language), [language])
  const setLanguage = useCallback((nextLanguage) => {
    const next = new URLSearchParams(params)
    if (nextLanguage === 'ar') next.set('lang', 'ar')
    else next.delete('lang')
    setParams(next, { replace: true })
  }, [params, setParams])
  const path = useCallback((target) => aivexPath(target, language), [language])
  return { language, isArabic, dir: isArabic ? 'rtl' : 'ltr', t, setLanguage, path }
}

